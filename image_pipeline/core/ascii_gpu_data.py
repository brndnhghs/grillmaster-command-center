# ── Character set presets ─────────────────────────────────────────────
# Each preset is a list of character indices (0..94) forming a subset of
# the full 95 printable ASCII range. Indices map to chr(idx + 32).
_CHARSET_PRESETS: dict[str, list[int]] = {
    "full":     list(range(95)),
    "classic":  [0, 14, 26, 27, 1, 12, 13, 29, 11, 10, 3, 5, 32],
    "minimal":  [0, 14, 26, 10, 32],
    "dense":    [0, 14, 26, 13, 11, 10, 3, 5, 32],
    "letters":  [i for i in range(95) if chr(i + 32).isalpha()],
    "caps":     [i for i in range(95) if chr(i + 32).isupper()],
    "lower":    [i for i in range(95) if chr(i + 32).islower()],
    "symbols":  [i for i in range(95) if not chr(i + 32).isalnum() and not chr(i + 32).isspace()],
    "digits":   [i for i in range(95) if chr(i + 32).isdigit()],
    "wide":     [0, 3, 5, 6, 32, 34, 40, 45, 46, 47, 49, 50, 24, 16],
    "sharp":    [0, 1, 7, 12, 13, 14, 15, 26, 27, 28, 30, 56, 60, 62, 63, 92],
    "half":     [0, 76, 73, 65, 79, 32],
}

# Human-readable names for the UI choice dropdown
CHARSET_CHOICES = ["full", "classic", "minimal", "dense", "letters", "caps", "lower",
                   "symbols", "digits", "wide", "sharp", "half"]

# Max preset size (for padded GLSL arrays)
MAX_PRESET_SIZE = max(len(v) for v in _CHARSET_PRESETS.values())  # 95 (full set)


def get_charset_indices(name: str) -> list[int]:
    """Return the character indices for a named preset.

    Args:
        name: Preset name from CHARSET_CHOICES or a comma-separated list
              of character indices for custom sets.

    Returns:
        List of character indices (0..94).
    """
    if name in _CHARSET_PRESETS:
        return list(_CHARSET_PRESETS[name])
    # Try to parse as a custom list: "0,14,26,10,32" or "32,33,34"
    try:
        parts = [int(p.strip()) for p in name.split(",")]
        if all(0 <= p < ASCII_CHAR_COUNT for p in parts):
            return parts
    except (ValueError, TypeError):
        pass
    # Try as a literal character string: " .:*@"
    indices = [ord(c) - 32 for c in name if 32 <= ord(c) <= 126]
    if indices:
        return indices
    raise ValueError(
        f"Unknown charset '{name}'. Choose from: {', '.join(CHARSET_CHOICES)}, "
        f"or pass a comma-separated list of indices, or a literal character string."
    )


def charset_for_glsl(name: str) -> tuple[int, list[int]]:
    """Return (preset_count, padded_indices) for GLSL embedding.

    The indices are padded to MAX_PRESET_SIZE with -1 sentinels.
    """
    indices = get_charset_indices(name)
    padded = indices + [-1] * (MAX_PRESET_SIZE - len(indices))
    return len(indices), padded


# Build flat GLSL arrays for all presets (each padded to MAX_PRESET_SIZE)
# Shape: CHARSET_PRESETS_DATA[num_presets * MAX_PRESET_SIZE]
CHARSET_PRESET_NAMES: list[str] = CHARSET_CHOICES
CHARSET_PRESETS_DATA: list[int] = []
for pname in CHARSET_PRESET_NAMES:
    _, padded = charset_for_glsl(pname)
    CHARSET_PRESETS_DATA.extend(padded)
